import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
const source=path.dirname(fileURLToPath(import.meta.url));
const dir=path.resolve(source,'../tools');
const url='https://www.gyan.dev/ffmpeg/builds/packages/ffmpeg-9.0.2-essentials_build.zip';
const archive=path.join(dir,'ffmpeg-9.0.2-essentials_build.zip');
const check=await fetch(url,{headers:{Range:'bytes=0-0'},signal:AbortSignal.timeout(30000)});
if(check.status!==206)throw new Error('Origem não suporta download parcial.');
const total=Number(check.headers.get('content-range')?.split('/')[1]);await check.arrayBuffer();
if(!Number.isSafeInteger(total)||total<1000000)throw new Error('Tamanho inválido.');
fs.mkdirSync(dir,{recursive:true});
if(!fs.existsSync(archive))fs.writeFileSync(archive,Buffer.alloc(0));
const start=fs.statSync(archive).size;
if(start>total)throw new Error('Arquivo parcial maior que origem.');
const width=Math.ceil((total-start)/4);
console.log(JSON.stringify({resumeBytes:start,totalBytes:total}));
const pieces=await Promise.all(Array.from({length:4},async(_,i)=>{
 const a=start+i*width,b=Math.min(total-1,a+width-1);if(a>b)return null;
 const response=await fetch(url,{headers:{Range:`bytes=${a}-${b}`},signal:AbortSignal.timeout(240000)});
 if(response.status!==206||response.headers.get('content-range')!==`bytes ${a}-${b}/${total}`)throw new Error('Intervalo inválido.');
 const buffer=Buffer.from(await response.arrayBuffer());if(buffer.length!==b-a+1)throw new Error('Parte incompleta.');
 const file=path.join(dir,`ffmpeg-part-${i}.bin`);fs.writeFileSync(file,buffer);console.log(JSON.stringify({part:i,bytes:buffer.length}));return file;
}));
for(const file of pieces)if(file)fs.appendFileSync(archive,fs.readFileSync(file));
const hash=crypto.createHash('sha256').update(fs.readFileSync(archive)).digest('hex');
if(hash!=='60f467265b1e312373dbcd92200c2618a74850f98d3d078e94296bb3fa2047ba')throw new Error('Checksum oficial não confere.');
console.log(JSON.stringify({verified:true,sha256:hash,bytes:total}));
